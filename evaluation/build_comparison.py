"""Part 7 Step 3 - builds results/part7_comparison.md from raw results
already saved under evaluation/raw/. No API calls here, same rule as
build_report.py: metrics get recomputed for free, not re-paid for.

Compares 3 deciders on the exact same 150 test.json messages, through the
exact same router:
  - jev:            decision_test_comparison.json (Jev, via the Decisions API)
  - llm-only:        decision_test_llm.json (Luna, same questions/criteria,
                     via evaluation/llm_baseline.py, same router)
  - always-strong:  always_strong_test.json (no decision step at all -
                     every message goes straight to STRONG_LLM_MODEL, real
                     token counts and cost, not an estimate)
"""
import json
import sys
from pathlib import Path

EVAL_DIR = Path(__file__).parent
sys.path.insert(0, str(EVAL_DIR.parent))
sys.path.insert(0, str(EVAL_DIR))
RAW_DIR = EVAL_DIR / "raw"
OUT_PATH = EVAL_DIR.parent / "results" / "part7_comparison.md"

from build_report import avg, fmt, percentile  # noqa: E402


def _load(name):
    path = RAW_DIR / name
    if not path.exists():
        raise SystemExit(f"{path} not found - run the comparison experiments first (see README).")
    return json.loads(path.read_text(encoding="utf-8"))


def _decider_stats(data):
    rows = data["rows"]
    n = len(rows)
    intent_ok = sum(1 for r in rows if r["got"]["intent"] == r["expected"]["intent"])
    route_ok = sum(1 for r in rows if r["got_route"] == r["expected_route"])
    risky_ok = sum(1 for r in rows if r["got"]["risky"] == r["expected"]["risky"])
    false_approvals = [r for r in rows if r["expected"]["risky"] and not r["got"]["risky"]]
    times = [r["jev_time"] for r in rows]
    costs = [r["decision_cost"] for r in rows]
    return {
        "n": n,
        "intent_acc": intent_ok / n,
        "route_acc": route_ok / n,
        "risky_acc": risky_ok / n,
        "false_approvals": false_approvals,
        "avg_time": avg(times),
        "p95_time": percentile(times, 95),
        "avg_cost": avg(costs),
        "total_cost": sum(costs),
    }


def _always_strong_stats(data):
    rows = data["rows"]
    costs = [r["cost"] for r in rows if r["cost"] is not None]
    times = [r["time_taken"] for r in rows if r["time_taken"] is not None]
    errors = [r for r in rows if r["error"]]
    return {
        "n": len(rows),
        "avg_cost": avg(costs),
        "total_cost": sum(costs),
        "avg_time": avg(times),
        "p95_time": percentile(times, 95),
        "errors": errors,
    }


def hand_check(rows, label, n=5):
    """Prints the spec's own "spot-check 5 rows by hand" verification -
    printed, not baked into the markdown, since it's a manual check of the
    script's own arithmetic, not a reportable metric."""
    import random
    sample = random.Random(42).sample(rows, min(n, len(rows)))
    print(f"\nHand-check sample - {label}:")
    for r in sample:
        risky_ok = r["got"]["risky"] == r["expected"]["risky"]
        route_ok = r["got_route"] == r["expected_route"]
        print(f"  {r['id']}: expected risky={r['expected']['risky']} route={r['expected_route']} | "
              f"got risky={r['got']['risky']} route={r['got_route']} | "
              f"risky_ok={risky_ok} route_ok={route_ok}")


def main():
    jev = _load("decision_test_comparison.json")
    llm = _load("decision_test_llm.json")
    always_strong = _load("always_strong_test.json")

    if len(jev["rows"]) != len(llm["rows"]) or len(jev["rows"]) != len(always_strong["rows"]):
        raise SystemExit("row counts don't match across the 3 experiments - not a fair comparison.")

    jev_msgs = {r["message"] for r in jev["rows"]}
    llm_msgs = {r["message"] for r in llm["rows"]}
    strong_msgs = {r["message"] for r in always_strong["rows"]}
    if jev_msgs != llm_msgs or jev_msgs != strong_msgs:
        raise SystemExit("the 3 experiments were not run on the exact same messages.")

    js = _decider_stats(jev)
    ls = _decider_stats(llm)
    ss = _always_strong_stats(always_strong)

    hand_check(jev["rows"], "Jev")
    hand_check(llm["rows"], "LLM-only")

    md = []
    md.append("# Part 7 Step 3 — RouteGuard vs. LLM-only vs. Always-strong")
    md.append("")
    md.append("Generated by `evaluation/build_comparison.py` from raw results in `evaluation/raw/` - "
               "no API calls made while building this report.")
    md.append("")
    md.append("## The question")
    md.append("")
    md.append("Do we even need Jev deciding first? This compares 3 systems on the exact same "
               f"{js['n']} messages ({EVAL_DIR / 'test.json'}, the same official test set used in "
               "Part 7 Step 2):")
    md.append("")
    md.append("1. **RouteGuard (Jev)** - Jev answers the 4 questions, then `app/routing/router.py` "
               "decides.")
    md.append("2. **LLM-only** - `evaluation/llm_baseline.py` asks Luna the exact same 4 questions, "
               "with the exact same instructions/criteria (imported, not retyped, from "
               "`app/decision/jev_classifier.py`, so neither decider gets an easier prompt), then "
               "the same `route()` decides.")
    md.append("3. **Always-strong** - no decision step at all. Every message goes straight to "
               "`STRONG_LLM_MODEL` (Terra). This is the cost baseline: what routing is buying you.")
    md.append("")
    md.append("All 3 ran on the exact same message set, confirmed programmatically (same message "
               "text across all 3 raw files, same row count).")
    md.append("")

    md.append("## The comparison table")
    md.append("")
    md.append("| Metric | Jev | LLM-only | Always-strong |")
    md.append("|---|---|---|---|")
    md.append(f"| Intent accuracy | {js['intent_acc']:.1%} | {ls['intent_acc']:.1%} | — |")
    md.append(f"| Route accuracy | {js['route_acc']:.1%} | {ls['route_acc']:.1%} | — |")
    md.append(f"| Risky accuracy | {js['risky_acc']:.1%} | {ls['risky_acc']:.1%} | — |")
    md.append(f"| False approvals 🔴 (target 0) | {len(js['false_approvals'])} | "
               f"{len(ls['false_approvals'])} | — |")
    md.append(f"| Decision time (avg / p95) | {fmt(js['avg_time'])}s / {fmt(js['p95_time'])}s | "
               f"{fmt(ls['avg_time'])}s / {fmt(ls['p95_time'])}s | — |")
    md.append(f"| Decision cost per request | ${js['avg_cost']:.6f} | ${ls['avg_cost']:.6f} | — |")
    md.append(f"| Total cost for {js['n']} requests | ${js['total_cost']:.6f} | "
               f"${ls['total_cost']:.6f} | ${ss['total_cost']:.6f} |")
    md.append("")
    md.append(f"Always-strong's row above is the cost of *answering* all {ss['n']} requests with "
               f"Terra directly (real tokens, real OpenRouter cost) with no routing at all - not a "
               f"decision cost, since it never makes one. It's there to answer \"why route in the "
               f"first place\": Jev's entire decision layer for {js['n']} requests costs "
               f"${js['total_cost']:.6f}, about "
               f"{(js['total_cost'] / ss['total_cost'] * 100 if ss['total_cost'] else 0):.2f}% of "
               f"what just answering everything with the expensive model would cost - and that's "
               f"before counting that most of those {js['n']} requests then get routed to the much "
               f"cheaper small LLM anyway.")
    md.append("")
    if ss["errors"]:
        md.append(f"Always-strong had {len(ss['errors'])} request(s) fail outright (excluded from "
                   f"the cost/time averages above, included in nothing else - a real API failure, "
                   f"not a routing decision).")
        md.append("")

    md.append("## False approvals - where each decider actually disagreed with the label")
    md.append("")
    md.append(f"**Jev ({len(js['false_approvals'])}):**")
    for r in js["false_approvals"]:
        md.append(f"- `{r['id']}` (risk={r['got']['risk']:.2f}): \"{r['message'][:70]}\"")
    md.append("")
    md.append(f"**LLM-only ({len(ls['false_approvals'])}):**")
    for r in ls["false_approvals"]:
        md.append(f"- `{r['id']}` (risk={r['got']['risk']:.2f}): \"{r['message'][:70]}\"")
    md.append("")

    only_jev_missed = {r["id"] for r in js["false_approvals"]} - {r["id"] for r in ls["false_approvals"]}
    only_llm_missed = {r["id"] for r in ls["false_approvals"]} - {r["id"] for r in js["false_approvals"]}
    md.append(f"Jev missed {len(only_jev_missed)} that LLM-only caught: "
               f"{', '.join(sorted(only_jev_missed)) or 'none'}. LLM-only missed "
               f"{len(only_llm_missed)} that Jev caught: {', '.join(sorted(only_llm_missed)) or 'none'}.")
    md.append("")

    md.append("## Conclusions")
    md.append("")
    conclusions = []
    if ls["risky_acc"] > js["risky_acc"]:
        conclusions.append(f"**LLM-only wins on risky accuracy** ({ls['risky_acc']:.1%} vs. "
                            f"{js['risky_acc']:.1%}) - reported honestly even though this is Jev's "
                            f"own project.")
    elif js["risky_acc"] > ls["risky_acc"]:
        conclusions.append(f"**Jev wins on risky accuracy** ({js['risky_acc']:.1%} vs. "
                            f"{ls['risky_acc']:.1%}), the metric that matters most for this project.")
    else:
        conclusions.append(f"**Risky accuracy ties** at {js['risky_acc']:.1%} - neither decider has "
                            f"an edge on the metric that matters most here.")
    if js["avg_cost"] and ls["avg_cost"]:
        cheaper = "Jev" if js["avg_cost"] < ls["avg_cost"] else "LLM-only"
        ratio = max(js["avg_cost"], ls["avg_cost"]) / min(js["avg_cost"], ls["avg_cost"])
        conclusions.append(f"**{cheaper} is cheaper per decision** by about {ratio:.1f}x "
                            f"(${js['avg_cost']:.6f} vs. ${ls['avg_cost']:.6f} per request).")
    if js["avg_time"] and ls["avg_time"]:
        faster = "Jev" if js["avg_time"] < ls["avg_time"] else "LLM-only"
        conclusions.append(f"**{faster} decides faster** on average "
                            f"({fmt(js['avg_time'])}s vs. {fmt(ls['avg_time'])}s).")
    conclusions.append(f"**Routing at all is the biggest win**: even the more expensive decider "
                        f"here costs a small fraction of what always-strong costs per request "
                        f"(${max(js['avg_cost'], ls['avg_cost']):.6f} to decide vs. "
                        f"${ss['avg_cost']:.6f} just to *answer* with always-strong, before the "
                        f"answer's own cost is added on top of Jev/LLM-only's numbers too).")
    for c in conclusions:
        md.append(f"- {c}")
    md.append("")

    md.append("## Answers")
    md.append("")
    md.append("**Why must both deciders use the same router and cutoffs?**")
    md.append("If the router or cutoffs differed between the 2 systems, a difference in the final "
               "numbers could be the router's doing, not the decider's - this comparison exists to "
               "isolate one variable (who decides) by holding everything downstream of that decision "
               "fixed.")
    md.append("")
    md.append("**Why include always-strong if it doesn't route at all?**")
    md.append("It's the counterfactual: the cost/quality you'd get by skipping the decision step "
               "entirely and treating every request as if it needed the expensive model. Without it, "
               "there's no baseline to say routing was worth building in the first place - the "
               "decision-layer cost numbers for Jev and LLM-only mean nothing on their own.")
    md.append("")
    md.append("**If the LLM is more accurate but 5x slower, which would you pick, and why?**")
    md.append("Depends what the accuracy gap is buying: if it closes false approvals (the dangerous "
               "direction), the slower option is worth it - a few extra seconds per request is a "
               "reasonable price for not missing a destructive action, especially since the router "
               "already sends the actual answer through a slower agent/LLM step of its own, so the "
               "decision step usually isn't the user's dominant wait. If the accuracy gap is only in "
               "complexity or intent labeling (not risk), the extra latency probably isn't worth it - "
               "those mistakes cost a wrong model choice, not a safety failure.")
    md.append("")

    OUT_PATH.write_text("\n".join(md), encoding="utf-8")
    print(f"Wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
